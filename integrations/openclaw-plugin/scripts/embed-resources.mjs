// Produce literal resources for the official single-backend artifact contract.
// No module-relative resource reads remain in the compiled backend.
import { createHash } from 'node:crypto';
import { lstatSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export function embedResources() {
  const assets = {}, hashes = {};
  function walk(directory, prefix = '') {
    for (const name of readdirSync(directory).sort()) {
      if (name.startsWith('.')) throw new Error('Hidden app resources are not permitted');
      const path = join(directory, name), stat = lstatSync(path);
      const relative = prefix + name;
      if (stat.isSymbolicLink()) throw new Error('Symlink app resources are not permitted');
      if (stat.isDirectory()) walk(path, relative + '/');
      else {
        if (!stat.isFile() || stat.nlink !== 1 || stat.size > 16 * 1024 * 1024) throw new Error('App resources must be bounded regular files');
        const bytes = readFileSync(path);
        assets[relative] = bytes.toString('base64');
        hashes[relative] = createHash('sha256').update(bytes).digest('hex');
      }
    }
  }
  walk('app');
  for (const name of ['index.html', 'stocks.index.json']) if (!assets[name]) throw new Error(`Missing original app resource: ${name}`);
  if (!Object.keys(assets).some(name => /^assets\/.*\.css$/.test(name)) || !Object.keys(assets).some(name => /^assets\/.*\.js$/.test(name))) throw new Error('Original app CSS and chunks must be staged before building');
  const css = readFileSync('static/overview.css', 'utf8');
  const text = '// Generated by scripts/embed-resources.mjs; do not edit.\n'
    + `export const OVERVIEW_CSS_TEXT = ${JSON.stringify(css)};\n`
    + `export const BUNDLED_APP_ASSETS: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(assets)});\n`
    + `export const BUNDLED_APP_ASSET_HASHES: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(hashes)});\n`;
  const destination = 'src/resources.generated.ts';
  let current; try { current = readFileSync(destination, 'utf8'); } catch {}
  if (current !== text) writeFileSync(destination, text);
  return { assets: Object.keys(assets).length };
}
